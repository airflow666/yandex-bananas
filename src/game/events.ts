/**
 * События забега.
 *
 * Симуляция складывает их в очередь, а разбирает тот, кому они нужны (сейчас
 * это звук). Смысл в том, чтобы `Session.update()` оставался чистой функцией
 * времени: его можно прогнать сотни шагов в тесте и проверить исход, не имея
 * ни аудиоконтекста, ни рендера.
 */

export type GameEvent =
  /** Ящик отцепился от лианы. */
  | { kind: 'drop' }
  /** Обычная посадка. */
  | { kind: 'land' }
  /** Идеальная посадка; streak — номер попадания в серии, задаёт высоту ноты. */
  | { kind: 'perfect'; streak: number }
  /** Ящик обрезало; severity 0..1 — насколько грубо. */
  | { kind: 'trim'; severity: number }
  /** Промах и конец забега. */
  | { kind: 'collapse' }
  /** Побит рекорд — ставится не симуляцией, а тем, кто владеет сохранениями. */
  | { kind: 'record' };
