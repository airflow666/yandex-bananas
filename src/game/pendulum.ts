/**
 * Маятник — источник тайминга.
 *
 * В прошлой версии блок ходил линейно с постоянной скоростью и отскакивал от
 * краёв. Это худший из возможных вариантов: скорость всюду одинакова, окно
 * для точного нажатия одно и то же в любой точке, и тайминг нечитаем.
 *
 * Настоящий маятник задаётся синусом: у краёв он почти останавливается, в
 * центре разгоняется до максимума. Именно эта неравномерность создаёт
 * «окно мастерства» — попасть в центр трудно, попасть у края легко, и игрок
 * сам решает, рисковать или ждать.
 */

export class Pendulum {
  /** Фаза колебания в радианах. */
  private phase = 0;

  /** Амплитуда в логических единицах — половина размаха. */
  amplitude = 260;

  /** Центр колебания по горизонтали. */
  centerX = 0;

  constructor(centerX: number, amplitude: number) {
    this.centerX = centerX;
    this.amplitude = amplitude;
    // Стартуем из крайнего положения: у игрока есть момент осмотреться,
    // а первое движение идёт медленно.
    this.phase = -Math.PI / 2;
  }

  /**
   * Угловая частота растёт с высотой, но замедляясь: логарифм не даёт
   * скорости уйти в абсурд к сотому этажу и при этом никогда не упирается
   * в потолок — в отличие от прежнего `min(..., 1120)`, после которого
   * сложность переставала меняться вообще.
   */
  static omegaFor(floors: number): number {
    const base = 1.9;
    return base * (1 + 0.35 * Math.log(1 + floors / 8));
  }

  /** Множитель скорости от режима: в шторме маятник на четверть быстрее. */
  speedScale = 1;

  update(dt: number, floors: number): void {
    this.phase += Pendulum.omegaFor(floors) * this.speedScale * dt;
    if (this.phase > Math.PI * 2) this.phase -= Math.PI * 2;
  }

  /** Текущая позиция центра блока. */
  get x(): number {
    return this.centerX + Math.sin(this.phase) * this.amplitude;
  }

  /**
   * Нормированная скорость (−1…1) — используется для наклона блока и троса:
   * визуальная обратная связь о том, где маятник «тяжёлый».
   */
  get velocityNorm(): number {
    return Math.cos(this.phase);
  }

  reset(): void {
    this.phase = -Math.PI / 2;
  }
}
