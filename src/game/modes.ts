/**
 * Режимы игры.
 *
 * «Шторм» — не отдельная игра и не копия кода, а НАБОР КОЭФФИЦИЕНТОВ к той же
 * симуляции. Это принципиально: любая правка баланса или физики автоматически
 * действует в обоих режимах, и они не могут разъехаться со временем.
 *
 * Чем шторм отличается по замыслу: в классике ветер — поздняя угроза, которая
 * появляется, когда игрок уже освоился (10-й этаж). В шторме он есть с самого
 * начала и вдвое сильнее, а маятник быстрее. Забег короче, цена ошибки выше,
 * рекорды считаются отдельно — сравнивать их с классикой было бы нечестно.
 */

export type GameMode = 'classic' | 'storm';

export interface ModeParams {
  /** Множитель скорости маятника. */
  speed: number;
  /** Множитель силы ветра. */
  wind: number;
  /**
   * С какого этажа появляется ветер. Значение может быть ОТРИЦАТЕЛЬНЫМ: сила
   * разгоняется от этого порога, поэтому −18 означает «на нулевом этаже ветер
   * уже разогнан примерно наполовину». Это дешевле отдельного параметра
   * «стартовая сила» и пользуется той же формулой разгона.
   */
  windFrom: number;
  /** Множитель награды — риск обязан окупаться. */
  reward: number;
}

export const MODES: Record<GameMode, ModeParams> = {
  classic: { speed: 1, wind: 1, windFrom: 10, reward: 1 },
  // Ветер уже разогнан на старте (см. windFrom) и вдвое сильнее; скорость
  // +25%. Награда в полтора раза: без этого в шторм никто не пойдёт второй раз.
  storm: { speed: 1.25, wind: 2, windFrom: -18, reward: 1.5 },
};

export function modeParams(mode: GameMode): ModeParams {
  return MODES[mode];
}
